#!/usr/bin/env node
/**
 * Generate src/app/environment/environment.production.ts from build-time env.
 *
 * Angular's @angular/build does not inline process.env in the browser bundle
 * (only NG_ / NG_APP_ prefixed vars are honored by the newer schematic, and
 * even then only for a specific set of frameworks). To keep this simple and
 * host-agnostic, we template the file at build time from Vercel's env vars.
 *
 * Vercel env vars this script honors (all optional):
 *   - NG_APP_API_URL       Fully-qualified API base URL (no trailing slash).
 *   - NG_APP_SENTRY_DSN    Sentry browser DSN. Blank disables reporting.
 *   - NG_APP_RELEASE       Release tag for Sentry (defaults to VERCEL_GIT_COMMIT_SHA).
 *
 * If NG_APP_API_URL is missing, the build fails loudly rather than shipping
 * a broken frontend that points at localhost.
 */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = resolve(process.cwd(), 'src/app/environment/environment.production.ts');

const apiUrl = process.env.NG_APP_API_URL;
if (!apiUrl || apiUrl.trim() === '') {
  console.error(
    '[generate-environment] NG_APP_API_URL is required at build time. ' +
      'Set it in Vercel > Project Settings > Environment Variables.',
  );
  process.exit(1);
}

const sentryDsn = (process.env.NG_APP_SENTRY_DSN ?? '').trim();
const release = (process.env.NG_APP_RELEASE ?? process.env.VERCEL_GIT_COMMIT_SHA ?? '').trim();

// The generated file must not import the Environment interface from
// './environment' — Angular's fileReplacements substitutes environment.ts
// with THIS file at build time, so the import would resolve back to this
// file itself (circular, and the interface wouldn't exist there anymore).
// Rely on structural typing from the object literal instead; consumers
// still get the correct shape via inference.
const contents = `// Generated by scripts/generate-environment.mjs at build time. Do not edit.
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl.replace(/\/+$/, ''))},
  sentryDsn: ${sentryDsn === '' ? 'null as string | null' : JSON.stringify(sentryDsn)},
  release: ${release === '' ? 'null as string | null' : JSON.stringify(release)},
};
`;

writeFileSync(target, contents, 'utf8');
console.log(`[generate-environment] wrote ${target}`);
console.log(`  apiUrl = ${apiUrl}`);
console.log(`  sentryDsn = ${sentryDsn === '' ? '(disabled)' : '(set)'}`);
console.log(`  release = ${release === '' ? '(none)' : release}`);
